#ifndef ESP_PANEL_CONFIG_H
#define ESP_PANEL_CONFIG_H

/**
 * @file esp_panel_config.h
 * @brief Configuration file for ESP Panel Drivers for the WT32-SC01-PLUS
 *
 * This file contains all the configurations needed for ESP Panel Drivers.
 * We disable all drivers by default and then enable only the ones we need
 * to minimize the final binary size.
 */

// *INDENT-OFF*

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////// Bus Configurations //////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#define ESP_PANEL_DRIVERS_BUS_USE_ALL        (0) // Disable all buses by default
#define ESP_PANEL_DRIVERS_BUS_USE_I80        (1) // Enable 8-bit Parallel bus for ST7796
#define ESP_PANEL_DRIVERS_BUS_USE_I2C        (1) // Enable I2C bus for FT5x06 Touch

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////// LCD Configurations ///////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#define ESP_PANEL_DRIVERS_LCD_USE_ALL        (0) // Disable all LCD drivers by default
#define ESP_PANEL_DRIVERS_LCD_USE_ST7796     (1) // Enable ST7796 driver

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////// Touch Configurations /////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#define ESP_PANEL_DRIVERS_TOUCH_MAX_POINTS   (5) // Maximum number of touch points supported
#define ESP_PANEL_DRIVERS_TOUCH_USE_ALL      (0) // Disable all touch drivers by default
#define ESP_PANEL_DRIVERS_TOUCH_USE_FT5x06   (1) // Enable FT5x06 driver

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////// Backlight Configurations ///////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#define ESP_PANEL_DRIVERS_BACKLIGHT_USE_ALL        (0) // Disable all backlight drivers by default
#define ESP_PANEL_DRIVERS_BACKLIGHT_USE_PWM_LEDC   (1) // Enable PWM (LEDC) backlight driver


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// ESP-LIB-UTILS CONFIGURATIONS
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////// Check Configurations /////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#define ESP_UTILS_CONF_CHECK_HANDLE_METHOD (ESP_UTILS_CHECK_HANDLE_WITH_ERROR_LOG)

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////// Log Configurations //////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#define ESP_UTILS_CONF_LOG_LEVEL (ESP_UTILS_LOG_LEVEL_INFO)

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////// Memory Configurations /////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#define ESP_UTILS_CONF_MEM_GEN_ALLOC_DEFAULT_ENABLE (1)
#define ESP_UTILS_CONF_MEM_GEN_ALLOC_TYPE           (ESP_UTILS_MEM_ALLOC_TYPE_ESP)
#if ESP_UTILS_CONF_MEM_GEN_ALLOC_TYPE == ESP_UTILS_MEM_ALLOC_TYPE_ESP
    #define ESP_UTILS_CONF_MEM_GEN_ALLOC_ESP_ALIGN (1)
    #define ESP_UTILS_CONF_MEM_GEN_ALLOC_ESP_CAPS  (MALLOC_CAP_DEFAULT | MALLOC_CAP_8BIT | MALLOC_CAP_SPIRAM)
#endif

// *INDENT-ON*

#endif /* ESP_PANEL_CONFIG_H */
